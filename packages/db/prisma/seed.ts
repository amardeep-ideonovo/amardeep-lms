// Categories shown as chips on class tiles and landing pages. The accent color
// each class renders in is resolved from these names (apps/web/lib/memberData.ts,
// apps/admin/lib/class-accent.ts, apps/mobile/src/class-colors.ts) — renaming a
// category here without updating those keyword lists silently re-colors the
// demo.
const CATEGORIES: Array<[string, string, number]> = [
  ["seed-lvlcat-food", "Food", 0],
  ["seed-lvlcat-fitness", "Fitness", 1],
  ["seed-lvlcat-music", "Music", 2],
];

async function seedCatalog() {
  for (const [id, name, order] of CATEGORIES) {
    await prisma.levelCategory.upsert({
      where: { id },
      update: { name, order },
      create: { id, name, order },
    });
  }

  for (const cls of CLASSES) {
    const levelId = `seed-class-${cls.key}`;
    const firstCourseId = `seed-course-${cls.courses[0].key}`;
    const levelData = {
      name: cls.name,
      slug: cls.slug,
      published: true,
      type: cls.type,
      description: cls.description,
      imageUrl: cls.imageUrl,
      trailerUrl: cls.trailerUrl,
      audienceTags: [cls.slug],
      skills: cls.skills as unknown as Prisma.InputJsonValue,
    };

    await prisma.level.upsert({
      where: { id: levelId },
      update: {
        ...levelData,
        categories: { set: cls.categories.map((id) => ({ id })) },
      },
      create: {
        id: levelId,
        ...levelData,
        categories: { connect: cls.categories.map((id) => ({ id })) },
      },
    });

    for (let c = 0; c < cls.courses.length; c++) {
      const course = cls.courses[c];
      const courseId = `seed-course-${course.key}`;
      const courseData = {
        title: course.title,
        slug: course.slug,
        description: course.description,
        order: c,
        published: true, // catalog courses are live (they carry lessons)
        thumbnailUrl: course.thumbnailUrl,
        coverImageUrl: course.coverImageUrl,
      };
      await prisma.course.upsert({
        where: { id: courseId },
        update: courseData,
        create: { id: courseId, ...courseData },
      });
      await prisma.courseLevel.upsert({
        where: { courseId_levelId: { courseId, levelId } },
        update: {},
        create: { courseId, levelId },
      });
      for (let l = 0; l < course.lessons.length; l++) {
        const lesson = course.lessons[l];
        const lessonId = `seed-lesson-${course.key}-${l + 1}`;
        const payload = {
          title: lesson.title,
          content: lesson.content,
          order: l,
          videoUrl: lesson.videoUrl,
          thumbnailUrl: lesson.thumbnailUrl,
          durationSeconds: lesson.durationSeconds,
        };
        await prisma.lesson.upsert({
          where: { id: lessonId },
          update: payload,
          create: { id: lessonId, courseId, ...payload },
        });
      }
    }

    await prisma.level.update({
      where: { id: levelId },
      data: { featuredCourseId: firstCourseId },
    });

    for (let p = 0; p < cls.prices.length; p++) {
      const price = cls.prices[p];
      const priceId = `seed-price-${cls.key}-${p + 1}`;
      await prisma.price.upsert({
        where: { id: priceId },
        update: {
          interval: price.interval,
          amount: price.amount,
          currency: "usd",
          active: true,
          installments: price.installments ?? null,
        },
        create: {
          id: priceId,
          levelId,
          stripePriceId: null,
          interval: price.interval,
          amount: price.amount,
          currency: "usd",
          active: true,
          installments: price.installments ?? null,
        },
      });
    }
  }
}
// ---------- retiring content the seed no longer defines ----------
// Upserts alone can only ADD: change the catalog and yesterday's classes stay
// in the database forever, which is how an already-seeded box would keep
// serving a retired class (and its old cover art) next to the new ones. Only
// SEED_WIPE=1 cleaned that up, and a wipe is far too blunt for a live demo —
// it drops the admin's own work and every uploaded file with it.
//
// So the seed retires its OWN leftovers: anything id-prefixed "seed-" that the
// current definitions don't produce. The prefix is the safety boundary — admin
// content gets cuid ids and can never match, so this cannot delete a client's
// work. Level/Course deletes cascade to prices, grants, joins, lessons,
// progress and certificates (schema.prisma), so no orphans survive.
async function retireStaleSeedRows() {
  const keepLevels = CLASSES.map((c) => `seed-class-${c.key}`);
  const keepCourses = [
    ...CLASSES.flatMap((c) => c.courses.map((co) => `seed-course-${co.key}`)),
    "seed-course-open", // QA fixtures — not part of the catalog, but seed-owned
    "seed-course-pro",
  ];
  const keepLessons = [
    ...CLASSES.flatMap((c) =>
      c.courses.flatMap((co) =>
        co.lessons.map((_, i) => `seed-lesson-${co.key}-${i + 1}`),
      ),
    ),
    "seed-lesson-open-1",
    "seed-lesson-open-2",
    "seed-lesson-pro-1",
  ];
  const keepPrices = CLASSES.flatMap((c) =>
    c.prices.map((_, i) => `seed-price-${c.key}-${i + 1}`),
  );

  // Children first, so a retired class's courses go before the class itself
  // (Course has no FK to Level — the join table does — so they'd orphan).
  const stale = async (
    label: string,
    n: Promise<{ count: number }>,
  ): Promise<void> => {
    const { count } = await n;
    if (count) console.log(`  retired ${count} stale seed ${label}`);
  };
  await stale(
    "lesson(s)",
    prisma.lesson.deleteMany({
      where: {
        id: { startsWith: "seed-lesson-" },
        NOT: { id: { in: keepLessons } },
      },
    }),
  );
  await stale(
    "course(s)",
    prisma.course.deleteMany({
      where: {
        id: { startsWith: "seed-course-" },
        NOT: { id: { in: keepCourses } },
      },
    }),
  );
  await stale(
    "price(s)",
    prisma.price.deleteMany({
      where: {
        id: { startsWith: "seed-price-" },
        NOT: { id: { in: keepPrices } },
      },
    }),
  );
  await stale(
    "class(es)",
    prisma.level.deleteMany({
      where: {
        id: { startsWith: "seed-class-" },
        NOT: { id: { in: keepLevels } },
      },
    }),
  );
  await stale(
    "category(ies)",
    prisma.levelCategory.deleteMany({
      where: {
        id: { startsWith: "seed-lvlcat-" },
        NOT: { id: { in: CATEGORIES.map(([id]) => id) } },
      },
    }),
  );
  await stale(
    "post(s)",
    prisma.post.deleteMany({
      where: {
        id: { startsWith: "seed-post-" },
        NOT: { id: { in: POST_IDS } },
      },
    }),
  );
  await stale(
    "post category(ies)",
    prisma.postCategory.deleteMany({
      where: {
        id: { startsWith: "seed-postcat-" },
        NOT: { id: { in: POST_CATEGORIES.map(([id]) => id) } },
      },
    }),
  );
  await stale(
    "post tag(s)",
    prisma.tag.deleteMany({
      where: {
        id: { startsWith: "seed-tag-" },
        NOT: { id: { in: POST_TAGS.map(([id]) => id) } },
      },
    }),
  );
}

// ---------- baseline purge: no demo debris on real client instances ----------
// A baseline boot (SEED_DEMO_CONTENT=false) used to stop at the first admin,
// which quietly grandfathered in any demo content the database already carried
// — an instance seeded with the demo once and later flipped to baseline kept
// the whole catalog forever. That is not hypothetical: a live client instance
// spent days publicly serving the retired demo (competitor-hotlinked art and
// all) plus the well-known member@example.com/member123 login, because nothing
// on the baseline path was allowed to delete anything.
//
// So the baseline path now removes everything the demo seed authors. Same
// safety boundary as retireStaleSeedRows(): only "seed-"-prefixed ids (client
// content gets cuids), plus three targeted extras —
//   - the Stripe Test fixture (known cuids from seedFixtureCluster),
//   - the demo member (example.com is reserved; no real member can own it),
//   - the Footer/AppConfig singletons ONLY on an exact fingerprint match with
//     the seeded copy. The singletons aren't seed-prefixed, and a client may
//     have customized them — an edited row breaks the fingerprint and is left
//     alone. The API default-merges neutral config when the row is absent.
async function purgeDemoDebris() {
  let removed = 0;
  const purge = async (n: Promise<{ count: number }>) => {
    removed += (await n).count;
  };

  // Explicit child→parent order, independent of cascade settings (the same
  // philosophy as wipeDatabase above).
  await purge(
    prisma.formSubmission.deleteMany({
      where: { formId: { startsWith: "seed-form-" } },
    }),
  );
  await purge(
    prisma.lesson.deleteMany({ where: { id: { startsWith: "seed-lesson-" } } }),
  );
  await purge(
    prisma.course.deleteMany({ where: { id: { startsWith: "seed-course-" } } }),
  );
  await purge(
    prisma.price.deleteMany({
      where: {
        OR: [
          { id: { startsWith: "seed-price-" } },
          {
            id: {
              in: ["cmpshpddz0003mtv6j4e4i1lz", "cmputofx10005kzsobri0mddw"],
            },
          },
        ],
      },
    }),
  );
  await purge(
    prisma.level.deleteMany({
      where: {
        OR: [
          { id: { startsWith: "seed-class-" } },
          { id: { startsWith: "seed-level-" } },
          { id: "cmpshpddy0002mtv65lh9p50c" }, // Stripe Test fixture
        ],
      },
    }),
  );
  await purge(
    prisma.levelCategory.deleteMany({
      where: { id: { startsWith: "seed-lvlcat-" } },
    }),
  );
  await purge(
    prisma.post.deleteMany({ where: { id: { startsWith: "seed-post-" } } }),
  );
  await purge(
    prisma.postCategory.deleteMany({
      where: { id: { startsWith: "seed-postcat-" } },
    }),
  );
  await purge(
    prisma.tag.deleteMany({ where: { id: { startsWith: "seed-tag-" } } }),
  );
  await purge(
    prisma.page.deleteMany({ where: { id: { startsWith: "seed-page-" } } }),
  );
  await purge(
    prisma.popup.deleteMany({ where: { id: { startsWith: "seed-popup-" } } }),
  );
  await purge(
    prisma.form.deleteMany({ where: { id: { startsWith: "seed-form-" } } }),
  );
  await purge(
    prisma.menuItem.deleteMany({
      where: { menuId: { startsWith: "seed-menu-" } },
    }),
  );
  await purge(
    prisma.menu.deleteMany({ where: { id: { startsWith: "seed-menu-" } } }),
  );
  await purge(
    prisma.header.deleteMany({ where: { id: { startsWith: "seed-header-" } } }),
  );
  await purge(
    prisma.certificateTemplate.deleteMany({
      where: { id: { startsWith: "seed-cert-template-" } },
    }),
  );

  // Seeded media: remove the copied files (key = filename in MEDIA_DIR), then
  // the gallery rows. Best-effort on disk — a missing file is already gone.
  const seedMedia = await prisma.mediaAsset.findMany({
    where: { id: { startsWith: "seed-media-" } },
    select: { key: true },
  });
  if (seedMedia.length) {
    const apiSrc = path.resolve(__dirname, "../../../apps/api/src");
    const mediaRoot =
      process.env.MEDIA_DIR || path.join(apiSrc, "media-uploads");
    for (const { key } of seedMedia) {
      try {
        fs.unlinkSync(path.join(mediaRoot, key));
      } catch {
        /* not on disk — nothing to remove */
      }
    }
    await purge(
      prisma.mediaAsset.deleteMany({
        where: { id: { startsWith: "seed-media-" } },
      }),
    );
  }

  await purge(
    prisma.user.deleteMany({ where: { email: "member@example.com" } }),
  );

  // Singletons, by exact seeded fingerprint only.
  const footer = await prisma.footer.findUnique({ where: { id: "singleton" } });
  if (
    footer &&
    JSON.stringify(footer.config).includes(
      "© {year} Spotlight Academy. All rights reserved.",
    )
  ) {
    await purge(prisma.footer.deleteMany({ where: { id: "singleton" } }));
  }
  const appCfg = await prisma.appConfig.findUnique({
    where: { id: "singleton" },
  });
  if (appCfg) {
    const cfg = appCfg.config as { title?: string; tagline?: string } | null;
    if (
      cfg?.title === "Spotlight Academy" &&
      cfg?.tagline === "Learn from the best. Love what you make."
    ) {
      await purge(prisma.appConfig.deleteMany({ where: { id: "singleton" } }));
    }
  }

  if (removed) {
    console.log(
      `  healed: removed ${removed} leftover demo-content row(s) — this instance runs without demo content.`,
    );
  }

  // With the demo gone, "demo seeded" is no longer true: clear the marker so
  // an instance later flipped back to SEED_DEMO_CONTENT=true seeds the demo
  // fresh instead of skipping it.
  await prisma.seedState.deleteMany();
}

// ---------- one-shot demo (SEED_DEMO_ONCE) ----------
// On provisioned instances the demo is a starting template, not an enforced
// state: the moment it lands it belongs to the client, and no later boot may
// resurrect a class they deleted or revert an image they changed. The SeedState
// row records that the demo has landed; its absence on a database that clearly
// carries demo content means the content predates the marker (seeded by an
// older image), so it is stamped as-is — never re-imposed.

const SEED_STATE_ID = "singleton";

async function demoAlreadySeeded(): Promise<boolean> {
  if (await prisma.seedState.findUnique({ where: { id: SEED_STATE_ID } })) {
    return true;
  }
  // Legacy footprint: any surviving demo row counts. Checked across several
  // tables (not just levels) so a client who deleted every demo class isn't
  // mistaken for a never-seeded instance and re-seeded over their work.
  const [levels, posts, pages, certs, member] = await Promise.all([
    prisma.level.count({
      where: {
        OR: [
          { id: { startsWith: "seed-class-" } },
          { id: { startsWith: "seed-level-" } },
        ],
      },
    }),
    prisma.post.count({ where: { id: { startsWith: "seed-post-" } } }),
    prisma.page.count({ where: { id: { startsWith: "seed-page-" } } }),
    prisma.certificateTemplate.count({
      where: { id: { startsWith: "seed-cert-template-" } },
    }),
    prisma.user.count({ where: { email: "member@example.com" } }),
  ]);
  return levels + posts + pages + certs + member > 0;
}

async function markDemoSeeded(): Promise<void> {
  // Create-only: the timestamp records the FIRST landing.
  await prisma.seedState.upsert({
    where: { id: SEED_STATE_ID },
    update: {},
    create: { id: SEED_STATE_ID, demoSeededAt: new Date() },
  });
}

// A control-plane "demo content pack" has been imported into this instance
// (see apps/api/src/content-pack). Its marker lives in ContentPackState — a
// table the seed never writes, kept separate from SeedState precisely so the
// baseline purge can consult it without racing its own SeedState wipe. When a
// pack is present, the baseline path must NOT purge: the pack was exported from
// a demo instance whose catalog still carried the seed's own "seed-" ids, and
// purgeDemoDebris() keys off exactly that prefix — it would delete the client's
// imported content on this and every later boot. Tolerant of the table being
// absent (an older schema) so the seed never crashes on it.
async function contentPackImported(): Promise<boolean> {
  try {
    return !!(await prisma.contentPackState.findUnique({
      where: { id: "singleton" },
    }));
  } catch {
    return false;
  }
}

